function http(name, { method, url, jsonBody, retry, timeout }, position, notes, mock) {
  const parameters = {
    method,
    url,
    options: { response: { response: { fullResponse: true, neverError: true } }, timeout },
  };
  if (mock) {
    parameters.authentication = 'none';
  } else {
    parameters.authentication = 'genericCredentialType';
    parameters.genericAuthType = 'httpHeaderAuth';
  }
  if (jsonBody) {
    parameters.sendBody = true;
    parameters.specifyBody = 'json';
    parameters.jsonBody = jsonBody;
  }
  const node = {
    parameters,
    name,
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position,
    onError: 'continueRegularOutput',
    notes,
  };
  if (!mock) node.credentials = WAVESPEED_CREDENTIAL_REF;
  if (retry) Object.assign(node, { retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 });
  else node.retryOnFail = false;
  return node;
}

