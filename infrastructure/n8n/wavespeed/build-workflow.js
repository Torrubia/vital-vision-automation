function code(name, body, position, extra = {}) {
  return {
    parameters: { jsCode: `// ${name}\n// GENERATED by infrastructure/n8n/wavespeed/build-workflow.js — edit src/ledger-core.js, not this node.\n\n${coreSource()}\n${HELPERS}\n// ---- node logic ----\n${body.trim()}\n` },
    name,
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position,
    ...extra,
  };
}

function ifRoute(name, route, position, notes) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
        conditions: [{
          id: `${name}-cond`.replace(/[^a-z0-9]+/gi, '-').toLowerCase(),
          leftValue: '={{ $json.route }}',
          rightValue: route,
          operator: { type: 'string', operation: 'equals' },
        }],
        combinator: 'and',
      },
      options: {},
    },
    name,
    type: 'n8n-nodes-base.if',
    typeVersion: 2.2,
    position,
    notes,
  };
}

const TABLE_RL = { __rl: true, mode: 'name', value: 'vv_wavespeed_generation_ledger' };

function schemaFor(values) {
  const typeOf = (k) => (k === 'estimated_cost_usd' ? 'number'
    : ['approved', 'published', 'requires_human_approval'].includes(k) ? 'boolean' : 'string');
  return Object.keys(values).map((k) => ({
    id: k, displayName: k, required: false, defaultMatch: false, display: true, type: typeOf(k), readOnly: false, removed: false,
  }));
}

