function parseArgs(argv) {
  const args = { out: DEFAULT_OUT, mockBaseUrl: null };
  for (let i = 2; i < argv.length; i++) {
    if (argv[i] === '--out') args.out = path.resolve(argv[++i]);
    else if (argv[i] === '--mock-base-url') args.mockBaseUrl = argv[++i];
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  return args;
}

function coreSource() {
  const src = fs.readFileSync(path.join(ROOT, 'src', 'ledger-core.js'), 'utf8');
  const cut = src.indexOf('// @@EXPORTS');
  if (cut < 0) throw new Error('ledger-core.js is missing the // @@EXPORTS marker');
  return src.slice(0, cut).trimEnd();
}

